// Build step for /support: create/update the support tables and seed ticket categories.
// Skips (and never fails the build) when the support database isn't configured, so the rest of the
// site still deploys. Runs `prisma db push`, which only touches the "support" schema in the URL.
import { execSync } from "node:child_process";

if (!process.env.SUPPORT_DATABASE_URL || !process.env.SUPPORT_DIRECT_URL) {
  console.log("[support] SUPPORT_DATABASE_URL / SUPPORT_DIRECT_URL not set: skipping support database setup.");
  process.exit(0);
}

const run = (cmd) => execSync(cmd, { stdio: "inherit" });

try {
  // --skip-generate: the client is already generated by postinstall.
  run("npx prisma db push --skip-generate");
  run("node prisma/seed-support.mjs");
} catch {
  // Surface the problem in the log, but let the main site deploy anyway; /support shows an error page.
  console.error("[support] database setup failed. /support will not work until this is fixed (see the error above).");
}
